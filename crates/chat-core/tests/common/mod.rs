//! Synthetic backups for integration tests, written in the export's HTML structure.

#![allow(dead_code)]

use std::path::{Path, PathBuf};

use chat_core::import::{import, ImportOptions, ImportReport};
use chat_core::Library;

pub const ME: &str = "Bob";

/// One message, written in chronological order by tests.
#[derive(Clone)]
pub struct M {
    pub sender: String,
    pub time: String,
    pub text: String,
    pub reaction: Option<(String, String)>,
    pub photo: Option<String>,
}

pub fn m(sender: &str, time: &str, text: &str) -> M {
    M {
        sender: sender.into(),
        time: time.into(),
        text: text.into(),
        reaction: None,
        photo: None,
    }
}

impl M {
    pub fn reacted(mut self, emoji: &str, by: &str) -> Self {
        self.reaction = Some((emoji.into(), by.into()));
        self
    }
    pub fn photo(mut self, file: &str) -> Self {
        self.photo = Some(file.into());
        self
    }
}

/// HTML of one `message_N.html` page in the export's structure (newest first).
pub fn page_html(title: &str, folder: &str, n: u32, total: u32, msgs: &[M]) -> String {
    let base = format!("your_instagram_activity/messages/inbox/{folder}");
    let mut links = String::new();
    for i in 1..=total {
        let class = if i == n { " class=\"selected\"" } else { "" };
        links.push_str(&format!(
            "<a{class} href=\"{base}/message_{i}.html\">{i}</a>"
        ));
    }
    let mut blocks = String::new();
    for msg in msgs.iter().rev() {
        let media = msg
            .photo
            .as_ref()
            .map(|f| format!("<div><div><a href=\"{base}/photos/{f}\"><img src=\"{base}/photos/{f}\" /></a><div></div></div></div>"))
            .unwrap_or_default();
        let reactions = msg
            .reaction
            .as_ref()
            .map(|(e, by)| format!("<div><ul><li><span>{e}{by}</span></li></ul></div>"))
            .unwrap_or_default();
        blocks.push_str(&format!(
            "<div><h2>{}</h2><div><div><div></div><div>{}</div><div></div><div></div>{media}{reactions}</div></div><div>{}</div></div>",
            msg.sender, msg.text, msg.time
        ));
    }
    format!(
        "<html><head><base href=\"../../../../\" /></head><body><header><h1>{title}</h1>\
         <aside>Generated by bob on <time datetime=\"2026-01-01T00:00Z\">x</time></aside></header>\
         <main><div>{links}</div>{blocks}</main></body></html>"
    )
}

/// Writes an export folder `instagram-bob-{date}-x` with one chat (`joy_111`) split
/// into pages of `per_page` messages (message_1 = newest). Returns the folder.
pub fn write_export(
    root: &Path,
    date: &str,
    title: &str,
    msgs: &[M],
    per_page: usize,
    photos: &[&str],
) -> PathBuf {
    write_chat(root, date, "joy_111", title, msgs, per_page, photos)
}

/// Like [`write_export`] for any chat folder; several chats can share one export.
pub fn write_chat(
    root: &Path,
    date: &str,
    folder: &str,
    title: &str,
    msgs: &[M],
    per_page: usize,
    photos: &[&str],
) -> PathBuf {
    let export = root.join(format!("instagram-bob-{date}-x"));
    let dir = export
        .join("your_instagram_activity/messages/inbox")
        .join(folder);
    std::fs::create_dir_all(dir.join("photos")).unwrap();
    let chunks: Vec<&[M]> = msgs.chunks(per_page.max(1)).collect();
    let total = chunks.len() as u32;
    for (i, chunk) in chunks.iter().enumerate() {
        let n = total - i as u32;
        std::fs::write(
            dir.join(format!("message_{n}.html")),
            page_html(title, folder, n, total, chunk),
        )
        .unwrap();
    }
    for p in photos {
        std::fs::write(dir.join("photos").join(p), format!("photo bytes {p}")).unwrap();
    }
    export
}

pub fn library(tmp: &Path) -> Library {
    Library::open(tmp.join("library")).unwrap()
}

pub fn run(lib: &mut Library, inputs: &[PathBuf]) -> ImportReport {
    import(lib, inputs, &ImportOptions::default()).unwrap()
}
