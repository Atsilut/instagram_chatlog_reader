//! Parser for one `message_N.html` page of Meta's Instagram HTML export.
//!
//! The export's CSS class names are obfuscated and may change between exports, so
//! messages are located by document structure instead: inside `<main>`, every `<h2>`
//! is a sender name, its next sibling is the content, and the parent's last child is
//! the timestamp.

use chrono::{DateTime, NaiveDateTime, Utc};
use scraper::{ElementRef, Html, Node, Selector};
use serde::Serialize;
use unicode_segmentation::UnicodeSegmentation;

#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct ParsedPage {
    /// Chat title from `<h1>` (the other person's display name, or the group name).
    pub title: String,
    /// Username in "Generated by {username} on ...".
    pub owner_username: Option<String>,
    pub generated_at: Option<DateTime<Utc>>,
    /// Thread folder named by the pagination links, so a lone file still knows its chat.
    pub thread: Option<ThreadRef>,
    /// N of this `message_N.html`, from the selected pagination link.
    pub page: Option<u32>,
    /// Highest page number in the pagination links (the chat's page count).
    pub page_count: Option<u32>,
    /// In document order, which is newest first.
    pub messages: Vec<ParsedMessage>,
    pub issues: Vec<ParseIssue>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct ThreadRef {
    /// `inbox` or `message_requests`.
    pub mailbox: String,
    /// e.g. `joy_1590353702351299`.
    pub folder: String,
    /// e.g. `1590353702351299`.
    pub thread_id: String,
}

#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct ParsedMessage {
    pub sender: String,
    /// Local wall-clock time as printed in the export (minute precision, no timezone).
    pub timestamp: NaiveDateTime,
    pub kind: MessageKind,
    pub text: Option<String>,
    pub parts: Vec<Part>,
    pub reactions: Vec<Reaction>,
    /// Original block HTML, kept when the block is empty or contains something unrecognized.
    pub raw_html: Option<String>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum MessageKind {
    Text,
    Media,
    Share,
    Link,
    /// "Reacted 😂 to your message"
    ReactionNotice,
    /// "Liked a message"
    Like,
    /// Nothing recognizable (unsent message, unsupported content, ...).
    Empty,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum Part {
    /// Paths are relative to the export root (the `instagram-*` folder).
    Photo {
        path: String,
    },
    Video {
        path: String,
    },
    Audio {
        path: String,
    },
    Gif {
        path: String,
    },
    File {
        path: String,
    },
    Share {
        caption: Option<String>,
        author: Option<String>,
        url: Option<String>,
    },
    Link {
        url: String,
        /// Page title from the link preview, when it differs from the URL.
        title: Option<String>,
    },
    RemoteGif {
        url: String,
    },
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Reaction {
    pub emoji: String,
    pub actor: String,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct ParseIssue {
    /// Index of the message block in the page.
    pub block: usize,
    pub message: String,
}

const TIMESTAMP_FORMAT: &str = "%b %d, %Y %I:%M %p";

pub fn parse_page(html: &str) -> ParsedPage {
    let doc = Html::parse_document(html);

    let title = doc
        .select(&sel("h1"))
        .next()
        .map(element_text)
        .unwrap_or_default();
    let (owner_username, generated_at) = parse_generated_by(&doc);
    let (thread, page, page_count) = parse_pagination(&doc);

    let mut messages = Vec::new();
    let mut issues = Vec::new();
    for (block, h2) in doc.select(&sel("main h2")).enumerate() {
        match parse_block(h2) {
            Ok(m) => messages.push(m),
            Err(message) => issues.push(ParseIssue { block, message }),
        }
    }

    ParsedPage {
        title,
        owner_username,
        generated_at,
        thread,
        page,
        page_count,
        messages,
        issues,
    }
}

pub fn parse_timestamp(s: &str) -> Option<NaiveDateTime> {
    NaiveDateTime::parse_from_str(s.trim(), TIMESTAMP_FORMAT).ok()
}

fn sel(css: &str) -> Selector {
    Selector::parse(css).expect("static selector")
}

fn parse_generated_by(doc: &Html) -> (Option<String>, Option<DateTime<Utc>>) {
    let Some(aside) = doc
        .select(&sel("aside"))
        .find(|a| element_text(*a).starts_with("Generated by "))
    else {
        return (None, None);
    };
    let text = element_text(aside);
    let owner = text
        .strip_prefix("Generated by ")
        .and_then(|rest| rest.split(" on ").next())
        .map(|s| s.trim().to_string())
        .filter(|s| !s.is_empty());
    let generated_at = aside
        .select(&sel("time"))
        .next()
        .and_then(|t| t.value().attr("datetime"))
        .and_then(parse_iso_minute);
    (owner, generated_at)
}

fn parse_iso_minute(s: &str) -> Option<DateTime<Utc>> {
    DateTime::parse_from_rfc3339(s)
        .map(|d| d.with_timezone(&Utc))
        .ok()
        .or_else(|| {
            NaiveDateTime::parse_from_str(s, "%Y-%m-%dT%H:%MZ")
                .ok()
                .map(|n| n.and_utc())
        })
}

fn parse_pagination(doc: &Html) -> (Option<ThreadRef>, Option<u32>, Option<u32>) {
    let mut thread = None;
    let mut page = None;
    let mut page_count: Option<u32> = None;
    for a in doc.select(&sel("main a[href]")) {
        let Some((t, n)) = a.value().attr("href").and_then(page_link) else {
            continue;
        };
        if a.value().classes().any(|c| c == "selected") {
            page = Some(n);
        }
        page_count = Some(page_count.map_or(n, |c| c.max(n)));
        thread.get_or_insert(t);
    }
    (thread, page, page_count)
}

/// Parses `.../messages/{mailbox}/{folder}/message_{n}.html`.
fn page_link(href: &str) -> Option<(ThreadRef, u32)> {
    let mut segs = href.rsplit('/');
    let file = segs.next()?;
    let folder = segs.next()?;
    let mailbox = segs.next()?;
    let n = file
        .strip_prefix("message_")?
        .strip_suffix(".html")?
        .parse()
        .ok()?;
    let thread_id = folder.rsplit_once('_').map(|(_, id)| id)?;
    if thread_id.is_empty() || !thread_id.bytes().all(|b| b.is_ascii_digit()) {
        return None;
    }
    Some((
        ThreadRef {
            mailbox: mailbox.to_string(),
            folder: folder.to_string(),
            thread_id: thread_id.to_string(),
        },
        n,
    ))
}

fn parse_block(h2: ElementRef) -> Result<ParsedMessage, String> {
    let block = h2
        .parent()
        .and_then(ElementRef::wrap)
        .ok_or("sender heading has no parent block")?;
    let sender = element_text(h2);
    let body = next_element_sibling(h2).ok_or("message block has no content")?;
    let time_el = block
        .children()
        .filter_map(ElementRef::wrap)
        .last()
        .filter(|el| el.id() != body.id() && el.id() != h2.id())
        .ok_or("message block has no timestamp")?;
    let time_text = element_text(time_el);
    let timestamp = parse_timestamp(&time_text)
        .ok_or_else(|| format!("unrecognized timestamp {time_text:?}"))?;

    let mut text = None;
    let mut parts = Vec::new();
    let mut reactions = Vec::new();
    let mut unknown = false;

    let slots: Vec<ElementRef> = body
        .children()
        .filter_map(ElementRef::wrap)
        .next()
        .map(|inner| inner.children().filter_map(ElementRef::wrap).collect())
        .unwrap_or_default();

    for (i, slot) in slots.iter().enumerate() {
        if let Some(ul) = slot.select(&sel("ul")).next() {
            reactions.extend(parse_reactions(ul));
        } else if is_blank(*slot) {
            continue;
        } else if i == 1 {
            text = Some(element_text(*slot)).filter(|t| !t.is_empty());
        } else if i == 2 {
            match parse_preview(*slot) {
                Some(p) => parts.push(p),
                None => unknown = true,
            }
        } else {
            let media = parse_media(*slot);
            if media.is_empty() {
                unknown = true;
            }
            parts.extend(media);
        }
    }

    // A pasted URL gets a preview shaped like a share (title + url); it's a link.
    for part in &mut parts {
        if let Part::Share {
            caption: None,
            author,
            url: Some(url),
        } = part
        {
            if text.as_deref() == Some(url.as_str()) {
                *part = Part::Link {
                    url: url.clone(),
                    title: author.take(),
                };
            }
        }
    }

    let has_share = parts.iter().any(|p| matches!(p, Part::Share { .. }));
    if has_share && text.as_deref().is_some_and(is_attachment_placeholder) {
        text = None;
    }

    let kind = classify(text.as_deref(), &parts);
    let raw_html = (unknown || kind == MessageKind::Empty).then(|| block.html());

    Ok(ParsedMessage {
        sender,
        timestamp,
        kind,
        text,
        parts,
        reactions,
        raw_html,
    })
}

fn classify(text: Option<&str>, parts: &[Part]) -> MessageKind {
    if let Some(t) = text {
        if t == "Liked a message" {
            return MessageKind::Like;
        }
        if t.starts_with("Reacted ") && t.ends_with(" to your message") {
            return MessageKind::ReactionNotice;
        }
    }
    let any = |f: fn(&Part) -> bool| parts.iter().any(f);
    if any(|p| matches!(p, Part::Share { .. })) {
        MessageKind::Share
    } else if any(|p| {
        matches!(
            p,
            Part::Photo { .. }
                | Part::Video { .. }
                | Part::Audio { .. }
                | Part::Gif { .. }
                | Part::File { .. }
                | Part::RemoteGif { .. }
        )
    }) {
        MessageKind::Media
    } else if any(|p| matches!(p, Part::Link { .. })) {
        MessageKind::Link
    } else if text.is_some() {
        MessageKind::Text
    } else {
        MessageKind::Empty
    }
}

/// "You sent an attachment." or "{name} sent an attachment."
fn is_attachment_placeholder(t: &str) -> bool {
    t.ends_with(" sent an attachment.")
}

fn parse_reactions(ul: ElementRef) -> Vec<Reaction> {
    ul.select(&sel("li"))
        .filter_map(|li| {
            let text = element_text(li);
            let mut graphemes = text.graphemes(true);
            let emoji = graphemes.next()?.to_string();
            let actor = graphemes.as_str().trim().to_string();
            Some(Reaction { emoji, actor })
        })
        .collect()
}

/// The slot after the text: a shared post/reel/story, a link preview, or a GIPHY link.
fn parse_preview(slot: ElementRef) -> Option<Part> {
    let inner = slot.children().filter_map(ElementRef::wrap).next()?;
    let fields: Vec<(String, Option<String>)> = inner
        .children()
        .filter_map(ElementRef::wrap)
        .map(|d| (element_text(d), first_href(d)))
        .collect();
    let nonempty = |s: &str| Some(s.to_string()).filter(|s| !s.is_empty());

    match fields.as_slice() {
        [(caption, None), (author, None), (_, Some(url))] => Some(Part::Share {
            caption: nonempty(caption),
            author: nonempty(author),
            url: Some(url.clone()),
        }),
        [(label, None), (_, Some(url))] if label == url => Some(Part::Link {
            url: url.clone(),
            title: None,
        }),
        [(author, None), (_, Some(url))] => Some(Part::Share {
            caption: None,
            author: nonempty(author),
            url: Some(url.clone()),
        }),
        [(_, Some(url))] if is_giphy(url) => Some(Part::RemoteGif { url: url.clone() }),
        [(_, Some(url))] => Some(Part::Link {
            url: url.clone(),
            title: None,
        }),
        [(author, None)] if !author.is_empty() => Some(Part::Share {
            caption: None,
            author: Some(author.clone()),
            url: None,
        }),
        _ => None,
    }
}

fn is_giphy(url: &str) -> bool {
    url.split('/')
        .nth(2)
        .is_some_and(|host| host.ends_with("giphy.com"))
}

/// Local attachments (`<img>`, `<video>`, `<audio>`, `<a>`) pointing into the export.
fn parse_media(slot: ElementRef) -> Vec<Part> {
    let mut seen: Vec<String> = Vec::new();
    let mut parts = Vec::new();
    for el in slot.descendants().filter_map(ElementRef::wrap) {
        let tag = el.value().name();
        let Some(path) = el.value().attr("src").or_else(|| el.value().attr("href")) else {
            continue;
        };
        if !is_local(path) || seen.iter().any(|p| p == path) {
            continue;
        }
        seen.push(path.to_string());
        let path = path.to_string();
        let part = match (media_folder(&path), tag) {
            (Some("videos"), _) | (_, "video") => Part::Video { path },
            (Some("audio"), _) | (_, "audio") => Part::Audio { path },
            (Some("gifs"), _) => Part::Gif { path },
            (Some("photos"), _) | (_, "img") => Part::Photo { path },
            _ => Part::File { path },
        };
        parts.push(part);
    }
    parts
}

fn is_local(path: &str) -> bool {
    !path.contains("://") && !path.starts_with("data:") && path.contains('/')
}

fn media_folder(path: &str) -> Option<&str> {
    let mut segs = path.rsplit('/');
    segs.next()?;
    segs.next()
}

fn first_href(el: ElementRef) -> Option<String> {
    el.select(&sel("a[href]"))
        .next()
        .and_then(|a| a.value().attr("href"))
        .map(str::to_string)
}

fn next_element_sibling(el: ElementRef) -> Option<ElementRef> {
    el.next_siblings().find_map(ElementRef::wrap)
}

fn is_blank(el: ElementRef) -> bool {
    el.text().all(|t| t.trim().is_empty())
        && !el
            .descendants()
            .filter_map(ElementRef::wrap)
            .any(|d| matches!(d.value().name(), "img" | "video" | "audio" | "a"))
}

/// Text content with `<br>` as newlines. Lines are trimmed because the export pads
/// `<br />` with spaces.
fn element_text(el: ElementRef) -> String {
    let mut out = String::new();
    for node in el.descendants() {
        match node.value() {
            Node::Text(t) => out.push_str(t),
            Node::Element(e) if e.name() == "br" => out.push('\n'),
            _ => {}
        }
    }
    let lines: Vec<&str> = out.lines().map(str::trim).collect();
    lines.join("\n").trim().to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_timestamps() {
        let t = parse_timestamp("Jul 18, 2025 2:15 pm").unwrap();
        assert_eq!(t.to_string(), "2025-07-18 14:15:00");
        let t = parse_timestamp("Jun 02, 2025 12:05 am").unwrap();
        assert_eq!(t.to_string(), "2025-06-02 00:05:00");
        assert!(parse_timestamp("yesterday").is_none());
    }

    #[test]
    fn parses_page_links() {
        let (t, n) = page_link(
            "your_instagram_activity/messages/inbox/joy_1590353702351299/message_41.html",
        )
        .unwrap();
        assert_eq!(n, 41);
        assert_eq!(t.mailbox, "inbox");
        assert_eq!(t.folder, "joy_1590353702351299");
        assert_eq!(t.thread_id, "1590353702351299");
        assert!(page_link("https://example.com/").is_none());
    }

    #[test]
    fn detects_giphy_hosts() {
        assert!(is_giphy("https://media3.giphy.com/media/x/200.gif"));
        assert!(!is_giphy("https://youtu.be/x"));
    }
}
